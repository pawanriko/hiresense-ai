# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
#
# TWO MODES, CHOSEN BY ONE ENVIRONMENT VARIABLE (DATABASE_URL):
#   * Unset (the default): SQLite, a single file (db.sqlite3) next to
#     manage.py. Zero setup — this is the learning setup, and it is what
#     the test suite uses. Nothing about your setup changes.
#   * Set: Postgres, e.g. a Supabase project (see the README's
#     "Supabase Postgres" section for how to create one and where to
#     copy the connection string from). The app then talks to Postgres
#     instead of the file — same models, same migrations, same code.
#     Your SQLite data does NOT move over: a Postgres database starts
#     empty, so you re-run migrate + seed_demo and re-upload resumes.
#     Switching back is just deleting DATABASE_URL from .env.
#
# WHY NO EXTRA LIBRARY: parsing a Postgres URL is ~15 lines with the
# standard library (urllib.parse), so we do it by hand instead of adding
# a dj-database-url dependency. One fewer package to learn and update.
# The only new dependency is the driver itself (psycopg, in
# requirements.txt) — Django's postgresql backend needs it to talk to
# a Postgres server at all.
from urllib.parse import urlparse, parse_qs, unquote


def _database_from_url(url):
    """Turn a Postgres connection URL into a Django DATABASES entry.

    Accepts the two URL shapes Supabase shows you:
      * Direct:  postgresql://postgres:<password>@db.<ref>.supabase.co:5432/postgres
      * Pooler:  postgresql://postgres.<ref>:<password>@aws-0-<region>.pooler.supabase.com:6543/postgres
    (``postgres://`` works too — same thing, older spelling.)
    Passwords and database names are URL-decoded, because Supabase
    passwords can contain characters like % or @ that must be escaped
    in a URL (e.g. p@ss becomes p%40ss).

    SSL: Supabase only accepts encrypted connections, so sslmode
    defaults to ``require`` when the URL doesn't say otherwise. An
    explicit sslmode in the URL is respected (it's your choice then),
    but we never silently turn SSL off — a URL without sslmode still
    gets require, not a plaintext connection.
    """
    parsed = urlparse(url)
    if parsed.scheme not in ('postgres', 'postgresql'):
        raise ValueError(
            'DATABASE_URL must start with postgres:// or postgresql://, '
            f'got {parsed.scheme!r}.'
        )
    # parse_qs gives lists (a key may repeat); we only care about the
    # first value of each key.
    query = {key: values[0] for key, values in parse_qs(parsed.query).items()}
    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': unquote(parsed.path.lstrip('/')) or 'postgres',
        'USER': unquote(parsed.username or ''),
        'PASSWORD': unquote(parsed.password or ''),
        'HOST': parsed.hostname or '',
        'PORT': str(parsed.port) if parsed.port else '',
        'OPTIONS': {'sslmode': query.get('sslmode', 'require')},
    }


DATABASE_URL = os.environ.get('DATABASE_URL', '').strip()
if DATABASE_URL:
    DATABASES = {'default': _database_from_url(DATABASE_URL)}
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


